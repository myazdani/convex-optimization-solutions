"""Compact publication and exact deterministic regeneration of large numerical inputs.

Raw local NPZ files can be omitted from publication; input_manifest.json records
canonical dtype, shape and SHA256 for every array. Regeneration uses the pinned
NumPy/SciPy algorithms and verifies every regenerated byte before returning it.
"""
from __future__ import annotations
import argparse,datetime,hashlib,json,shutil
from functools import lru_cache
from pathlib import Path
import numpy as np
from scipy import sparse
from scipy.optimize import brentq
from examples.algorithm_common import ROOT

LIMIT=256*1024

def array_record(value):
    a=np.ascontiguousarray(value)
    return {'shape':list(a.shape),'dtype':a.dtype.str,'sha256':hashlib.sha256(a.tobytes()).hexdigest()}


def dense_data(eid):
    if eid in ['fig_9_6','fig_9_7','fig_9_21']:
        from examples.algorithms_ch09 import dense_instance
        p=dense_instance();return {'A':p.A,'b':p.b,'c':p.c,'seed':np.array(906)}
    if eid=='fig_10_6':
        rg=np.random.default_rng(1006);A=rg.standard_normal((100,500));z0=rg.standard_normal(100);A+=np.outer(z0,1-A.T@z0)/(z0@z0);x0=rg.uniform(.01,1,500);b=A@x0
        return {'A':A,'b':b,'x0':x0,'z0':z0,'seed':np.array(1006)}
    if eid=='fig_11_17':
        from examples.algorithms_ch11 import sdp_instance
        p,x0=sdp_instance();return {'A':p.A,'b':p.B,'c':p.c,'x0':x0}
    raise ValueError(eid)


def sparse_instance():
    r=np.random.default_rng(923);n=10000;m=100000;N=200
    A1=sparse.random(400,50,density=.05,random_state=r,data_rvs=r.standard_normal,format='csr')
    A=sparse.vstack([sparse.eye(n),-sparse.eye(n),sparse.random(m-2*n,n,density=1e-6,random_state=r,data_rvs=r.standard_normal,format='csr')+sparse.kron(sparse.eye(N),A1)],format='csr')
    b=np.r_[np.ones(2*n),r.uniform(.001,1,m-2*n)];return A,b


@lru_cache(maxsize=1)
def self_concordant_data():
    from examples.algorithms_ch09 import LogBarrier,barrier_descent
    from scipy import linalg
    rg=np.random.default_rng(925);data={}
    for family,(m,n) in enumerate([(100,50),(1000,500),(1000,50)]):
        found=0
        while found<5:
            A=rg.standard_normal((m,n));b=rg.uniform(.001,1,m);p=LogBarrier(A,b)
            try:center=barrier_descent(p,alpha=.1,beta=.8,tol=1e-14,maxiter=20)
            except (linalg.LinAlgError,ValueError):continue
            if center['newton_decrement_squared']>1e-12:continue
            found+=1;xstar=center['x'];y=b-A@xstar;starts=[]
            for k in range(1,11):
                v=rg.standard_normal(n);dy=-A@v;smax=np.min(-y[dy<0]/dy[dy<0]);relative=dy/y;maxgap=-np.log1p((1-1e-6)*smax*relative).sum();target=k/10*maxgap
                s=brentq(lambda s:-np.log1p(s*relative).sum()-target,0,(1-1e-6)*smax,xtol=1e-14);starts.append(xstar+s*v)
            data[f'family{family+1}_problem{found}.npz']={'A':A,'b':b,'starts':np.array(starts),'xstar':xstar}
    return data


def regenerate(eid,filename):
    if eid=='fig_9_25':return self_concordant_data()[filename]
    if eid=='fig_9_23':
        A,b=sparse_instance()
        if filename=='A.npz':return {'indices':A.indices,'indptr':A.indptr,'format':np.array(b'csr'),'shape':np.array(A.shape),'data':A.data}
        return {'b':b,'seed':np.array(923)}
    if eid in ['fig_11_7','fig_11_19']:
        from examples.algorithm_scaling import standard_instance,sdp_matrix
        n=int(filename.removeprefix('instance_').removesuffix('.npz'));seed=(117000 if eid=='fig_11_7' else 111900)+n
        if eid=='fig_11_19':return {'B':sdp_matrix(n,seed),'seed':np.array(seed)}
        A,b,c,x,y,s=standard_instance(n,seed);return {'A':A,'b':b,'c':c,'x0':x,'y0':y,'s0':s,'seed':np.array(seed)}
    return dense_data(eid)


def load_data(eid,filename='instance.npz',force_regenerate=False):
    folder=ROOT/'artifacts/examples'/eid;path=folder/filename
    if path.exists() and not force_regenerate:
        with np.load(path) as z:arrays={k:z[k] for k in z.files}
    else:arrays=regenerate(eid,filename)
    manifest=json.loads((folder/'input_manifest.json').read_text());expected=manifest['files'][filename]['arrays']
    for key,record in expected.items():
        if array_record(arrays[key])!=record:raise ValueError(f'Regenerated input hash mismatch: {eid}/{filename}/{key}')
    return arrays


def load_sparse(eid='fig_9_23'):
    a=load_data(eid,'A.npz');return sparse.csr_matrix((a['data'],a['indices'],a['indptr']),shape=tuple(a['shape']))


def package(eid):
    folder=ROOT/'artifacts/examples'/eid;files={}
    for p in sorted(folder.glob('*.npz')):
        with np.load(p) as z:arrays={k:array_record(z[k]) for k in z.files}
        files[p.name]={'published_binary':p.stat().st_size<=LIMIT,'bytes':p.stat().st_size,'arrays':arrays}
    manifest={'schema_version':1,'id':eid,'generator':'PCG64 via pinned NumPy/SciPy; source implementation has explicit seeds and sampling order','files':files,
              'regeneration_command':f'OPENBLAS_NUM_THREADS=1 python -m examples.algorithm_evidence verify {eid}',
              'note':'Published binaries below256KiB are retained. Larger matrices are regenerated and each array is SHA256-checked. Raw numerical scope is unchanged.'}
    (folder/'input_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    p=folder/'results.json';r=json.loads(p.read_text());removed={}
    if eid=='fig_11_19':
        for name,run in r['runs'].items():
            if 'dual' in run:removed[f'runs.{name}.dual']=array_record(np.asarray(run.pop('dual')))
        if removed:
            shutil.copyfile(p,folder/'results.full.json');r['large_result_arrays']=removed
            r['certificate_reconstruction']='For each saved x, regenerate B, compute X=B+diag(x), W=X^-1, g=t-diag(W), H=W elementwise squared, dx=-H^-1 g, Z=(W-W diag(dx) W)/t. Saved objective/gap/eigenvalue/residual checks refer to this Z.'
    r['publication']={'packaged_at':datetime.datetime.now(datetime.timezone.utc).isoformat(),'implementation':'examples/algorithm_evidence.py','implementation_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                      'input_manifest_sha256':hashlib.sha256((folder/'input_manifest.json').read_bytes()).hexdigest(),'numeric_scope_reduced':False,
                      'verified_support_hashes':{'src/convex_solutions/plotting.py':hashlib.sha256((ROOT/'src/convex_solutions/plotting.py').read_bytes()).hexdigest()}}
    p.write_text(json.dumps(r,indent=2,allow_nan=False)+'\n')
    doc=ROOT/'docs/examples'/f'{eid}.md';s=doc.read_text();heading='\n## Compact input delivery\n'
    if heading in s:s=s.split(heading)[0]
    s+=heading+'\nGenerated inputs larger than 256 KiB are represented by [array hashes and regeneration metadata](../../artifacts/examples/'+eid+'/input_manifest.json). The [regeneration helper](../../examples/algorithm_evidence.py) reconstructs every omitted array and verifies its exact bytes under the pinned numerical environment. Run the original study command to materialize all inputs locally. No problem dimension, trial count or numerical accuracy is reduced.\n'
    if removed or 'large_result_arrays' in r:s+='\nThe order-1000 dual matrix is reconstructed from the saved final iterate using the explicit Newton correction described in the results JSON. Its gap, stationarity, primal and dual eigenvalue checks remain in the published result.\n'
    doc.write_text(s)
    return [str(x.relative_to(ROOT)) for x in folder.iterdir() if x.is_file() and x.name!='results.full.json' and (x.suffix!='.npz' or x.stat().st_size<=LIMIT)]

if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('action',choices=['package','verify']);ap.add_argument('id');a=ap.parse_args()
    if a.action=='package':package(a.id)
    else:
        m=json.loads((ROOT/'artifacts/examples'/a.id/'input_manifest.json').read_text())
        for filename,info in m['files'].items():
            if not info['published_binary']:load_data(a.id,filename,force_regenerate=True);print(filename,'verified')
